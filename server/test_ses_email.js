/**
 * Comprehensive Unit and Integration Test Suite for Amazon SES Email Service
 * AWS SDK for JavaScript v3 (@aws-sdk/client-ses)
 *
 * Validates:
 * 1. Mocked SESClient initialization and command parameter structure
 * 2. Successful delivery and receipt tracking
 * 3. Incomplete configuration rejection
 * 4. Invalid input and malformed recipient validation
 * 5. Provider error sanitization (no raw credentials/metadata leaked)
 * 6. HTML escaping on user-controlled template inputs (XSS prevention)
 * 7. All 9 application email templates dispatching correctly
 * 8. Startup connection verification (including least-privilege IAM)
 * 9. End-to-end integration with document expiry reminders and notification state
 */

const assert = require('assert');
const emailService = require('./src/services/email.service');
const { SendEmailCommand, GetSendQuotaCommand } = require('@aws-sdk/client-ses');

// Test harness state
let capturedCommands = [];
let mockClientBehavior = {
  sendQuotaSuccess: true,
  sendQuotaError: null,
  sendEmailSuccess: true,
  sendEmailError: null,
  messageIdCounter: 1000
};

// Create a mock SES client that records commands
const createMockSesClient = () => ({
  send: async (command) => {
    capturedCommands.push(command);

    if (command instanceof GetSendQuotaCommand || command.constructor.name === 'GetSendQuotaCommand') {
      if (!mockClientBehavior.sendQuotaSuccess) {
        throw mockClientBehavior.sendQuotaError || new Error('GetSendQuota failed');
      }
      return {
        Max24HourSend: 50000,
        MaxSendRate: 14,
        SentLast24Hours: 12
      };
    }

    if (command instanceof SendEmailCommand || command.constructor.name === 'SendEmailCommand') {
      if (!mockClientBehavior.sendEmailSuccess) {
        throw mockClientBehavior.sendEmailError || new Error('SES Send rejected');
      }
      mockClientBehavior.messageIdCounter++;
      return {
        MessageId: `ses-msg-${mockClientBehavior.messageIdCounter}-${Date.now()}`
      };
    }

    return { MessageId: `ses-default-${Date.now()}` };
  }
});

async function runSesTests() {
  console.log('================================================================');
  console.log('  DocTrack AI — Amazon SES Email Service Comprehensive Tests    ');
  console.log('================================================================\n');

  let passed = 0;
  let failed = 0;

  function recordPass(testName) {
    passed++;
    console.log(`  ✓ [PASS] ${testName}`);
  }

  function recordFail(testName, err) {
    failed++;
    console.error(`  ✗ [FAIL] ${testName}:`, err.message);
  }

  // Backup existing environment
  const originalRegion = process.env.AWS_REGION;
  const originalSender = process.env.SES_FROM_EMAIL;

  // Set test environment variables
  process.env.AWS_REGION = 'ap-south-1';
  process.env.SES_FROM_EMAIL = 'notifications@doctrack.ai';

  const mockClient = createMockSesClient();
  emailService.setSesClient(mockClient);

  // -------------------------------------------------------------
  // Test 1: Successful SES Send & Parameter Verification
  // -------------------------------------------------------------
  try {
    capturedCommands = [];
    mockClientBehavior.sendEmailSuccess = true;

    const result = await emailService.sendEmail({
      to: 'recipient@example.com',
      subject: 'Critical Expiry Notice',
      text: 'Your document expires soon.',
      html: '<p>Your document expires soon.</p>',
      type: 'EXPIRY_ALERT'
    });

    assert.strictEqual(result.success, true, 'Result success should be true');
    assert.strictEqual(result.delivered, true, 'Result delivered should be true');
    assert.strictEqual(result.mode, 'ses', 'Delivery mode must be ses');
    assert.ok(result.messageId.startsWith('ses-msg-'), 'MessageId must be generated by SES');
    assert.strictEqual(capturedCommands.length, 1, 'Exactly one SendEmailCommand must be dispatched');

    const cmd = capturedCommands[0];
    assert.strictEqual(cmd.input.Source, 'notifications@doctrack.ai', 'Source must match SES_FROM_EMAIL');
    assert.deepStrictEqual(cmd.input.Destination.ToAddresses, ['recipient@example.com'], 'Recipient must match');
    assert.strictEqual(cmd.input.Message.Subject.Data, 'Critical Expiry Notice');
    assert.strictEqual(cmd.input.Message.Body.Text.Data, 'Your document expires soon.');
    assert.strictEqual(cmd.input.Message.Body.Html.Data, '<p>Your document expires soon.</p>');

    recordPass('Test 1: Successful delivery with correct SES command structure');
  } catch (err) {
    recordFail('Test 1: Successful delivery with correct SES command structure', err);
  }

  // -------------------------------------------------------------
  // Test 2: Missing Configuration Rejection
  // -------------------------------------------------------------
  const config = require('./src/config/env');
  const savedConfigSender = config.ses?.fromEmail;

  try {
    if (config.ses) config.ses.fromEmail = '';
    delete process.env.SES_FROM_EMAIL;

    let threwExpected = false;
    try {
      await emailService.sendEmail({
        to: 'user@example.com',
        subject: 'Test',
        text: 'Body'
      });
    } catch (err) {
      if (err.message.includes('Amazon SES configuration is incomplete')) {
        threwExpected = true;
      }
    }

    assert.strictEqual(threwExpected, true, 'Must reject delivery when SES_FROM_EMAIL is unset');
    recordPass('Test 2: Rejects delivery on missing SES configuration');
  } catch (err) {
    recordFail('Test 2: Rejects delivery on missing SES configuration', err);
  } finally {
    if (config.ses) config.ses.fromEmail = savedConfigSender;
    process.env.SES_FROM_EMAIL = 'notifications@doctrack.ai';
  }

  // -------------------------------------------------------------
  // Test 3: Input Validation (Missing Recipient, Subject, Body)
  // -------------------------------------------------------------
  try {
    // A. Missing to
    let threwA = false;
    try {
      await emailService.sendEmail({ to: '', subject: 'Hi', text: 'Text' });
    } catch (e) {
      threwA = e.message.includes('Recipient, subject, and email body are required');
    }
    assert.ok(threwA, 'Must throw on missing to');

    // B. Missing subject
    let threwB = false;
    try {
      await emailService.sendEmail({ to: 'test@example.com', subject: '', text: 'Text' });
    } catch (e) {
      threwB = e.message.includes('Recipient, subject, and email body are required');
    }
    assert.ok(threwB, 'Must throw on missing subject');

    // C. Missing body
    let threwC = false;
    try {
      await emailService.sendEmail({ to: 'test@example.com', subject: 'Sub' });
    } catch (e) {
      threwC = e.message.includes('Recipient, subject, and email body are required');
    }
    assert.ok(threwC, 'Must throw on missing body');

    // D. Invalid email format
    let threwD = false;
    try {
      await emailService.sendEmail({ to: 'invalid-email-address', subject: 'Sub', text: 'Text' });
    } catch (e) {
      threwD = e.message.includes('Invalid recipient email address');
    }
    assert.ok(threwD, 'Must throw on invalid email format');

    recordPass('Test 3: Robust input validation for required fields & recipient structure');
  } catch (err) {
    recordFail('Test 3: Robust input validation for required fields & recipient structure', err);
  }

  // -------------------------------------------------------------
  // Test 4: Provider Error Handling & Sanitization
  // -------------------------------------------------------------
  try {
    mockClientBehavior.sendEmailSuccess = false;
    const awsError = new Error('MessageRejected: Email address is not verified in sandbox');
    awsError.name = 'MessageRejected';
    awsError.$metadata = { httpStatusCode: 400 };
    mockClientBehavior.sendEmailError = awsError;

    let sanitizedErrorThrown = false;
    try {
      await emailService.sendEmail({
        to: 'unverified@example.com',
        subject: 'Sandbox Test',
        text: 'Content'
      });
    } catch (err) {
      sanitizedErrorThrown = true;
      assert.ok(err.message.includes('Amazon SES delivery failed'), 'Error message must be sanitized');
      assert.strictEqual(err.code, 'MessageRejected');
      assert.strictEqual(err.statusCode, 400);
      assert.strictEqual(err.message.includes('AWS_SECRET_ACCESS_KEY'), false, 'Must never leak credentials');
    }

    assert.ok(sanitizedErrorThrown, 'Sanitized error should be thrown on provider failure');
    recordPass('Test 4: Provider errors sanitized without leaking AWS secrets or internal metadata');
  } catch (err) {
    recordFail('Test 4: Provider errors sanitized without leaking AWS secrets or internal metadata', err);
  } finally {
    mockClientBehavior.sendEmailSuccess = true;
    mockClientBehavior.sendEmailError = null;
  }

  // -------------------------------------------------------------
  // Test 5: HTML Escaping Utility & XSS Protection
  // -------------------------------------------------------------
  try {
    const maliciousPayload = '<script>alert("xss")</script> & "quotes" \'apostrophe\'';
    const escaped = emailService.escapeHtml(maliciousPayload);

    assert.strictEqual(
      escaped,
      '&lt;script&gt;alert(&quot;xss&quot;)&lt;/script&gt; &amp; &quot;quotes&quot; &#39;apostrophe&#39;'
    );
    assert.strictEqual(emailService.escapeHtml(null), '');
    assert.strictEqual(emailService.escapeHtml(undefined), '');

    recordPass('Test 5: HTML escaping utility correctly neutralizes injection vectors');
  } catch (err) {
    recordFail('Test 5: HTML escaping utility correctly neutralizes injection vectors', err);
  }

  // -------------------------------------------------------------
  // Test 6: Specialized Application Email Templates
  // -------------------------------------------------------------
  try {
    capturedCommands = [];

    // A. Welcome Email
    await emailService.sendWelcomeEmail({
      name: '<AdminUser>',
      email: 'welcome@example.com'
    });
    const welcomeCmd = capturedCommands[capturedCommands.length - 1];
    assert.ok(welcomeCmd.input.Message.Subject.Data.includes('Welcome to DocTrack AI'));
    assert.ok(welcomeCmd.input.Message.Body.Html.Data.includes('&lt;AdminUser&gt;'));

    // B. Verification Email
    await emailService.sendEmailVerification({
      email: 'verify@example.com'
    }, 'secret-token-xyz-123');
    const verifyCmd = capturedCommands[capturedCommands.length - 1];
    assert.ok(verifyCmd.input.Message.Subject.Data.includes('Verify your email address'));
    assert.ok(verifyCmd.input.Message.Body.Html.Data.includes('token=secret-token-xyz-123'));

    // C. Password Reset Token Email
    await emailService.sendPasswordReset({
      name: 'Reset User',
      email: 'reset@example.com'
    }, 'reset-token-456');
    const resetCmd = capturedCommands[capturedCommands.length - 1];
    assert.ok(resetCmd.input.Message.Subject.Data.includes('Password Reset Request'));
    assert.ok(resetCmd.input.Message.Body.Html.Data.includes('token=reset-token-456'));

    // D. Password Reset 6-Digit OTP Email
    await emailService.sendOtpEmail({
      name: 'Otp User',
      email: 'otp@example.com'
    }, '839201');
    const otpCmd = capturedCommands[capturedCommands.length - 1];
    assert.ok(otpCmd.input.Message.Subject.Data.includes('839201'));
    assert.ok(otpCmd.input.Message.Body.Html.Data.includes('839201'));

    // E. Document Expiry Reminder Email
    await emailService.sendDocumentExpiryReminder({
      user: { name: 'Holder', email: 'holder@example.com' },
      document: {
        _id: 'doc-12345',
        title: '<Driver License>',
        documentType: 'Driving License',
        expiryDate: '2026-12-31'
      },
      daysLeft: 14,
      threshold: 30
    });
    const expiryCmd = capturedCommands[capturedCommands.length - 1];
    assert.ok(expiryCmd.input.Message.Subject.Data.includes('expires in 14 days'));
    assert.ok(expiryCmd.input.Message.Body.Html.Data.includes('&lt;Driver License&gt;'));

    // F. Document Expired Notification Email
    await emailService.sendDocumentExpiredNotification({
      user: { name: 'Expired User', email: 'expired@example.com' },
      document: {
        _id: 'doc-expired',
        title: 'Work Visa',
        expiryDate: '2026-01-01'
      }
    });
    const expiredCmd = capturedCommands[capturedCommands.length - 1];
    assert.ok(expiredCmd.input.Message.Subject.Data.includes('EXPIRED'));

    // G. Renewal Reminder Checklist Email
    await emailService.sendRenewalReminder({
      user: { name: 'Renewal User', email: 'renew@example.com' },
      document: { title: 'Passport' },
      renewalGuide: { portalName: 'Passport Seva', officialFee: '₹1,500' }
    });
    const renewalCmd = capturedCommands[capturedCommands.length - 1];
    assert.ok(renewalCmd.input.Message.Subject.Data.includes('Renewal Assistant Guide'));

    // H. Warranty Expiry Notification Email
    await emailService.sendWarrantyExpiryNotification({
      user: { name: 'Warranty User', email: 'warranty@example.com' },
      warranty: { productName: 'MacBook Pro M2', expiryDate: '2026-11-20' },
      daysRemaining: 7
    });
    const warrantyCmd = capturedCommands[capturedCommands.length - 1];
    assert.ok(warrantyCmd.input.Message.Subject.Data.includes('MacBook Pro M2'));

    // I. Document Uploaded Confirmation Email
    await emailService.sendDocumentUploadedEmail({
      user: { name: 'Uploader', email: 'uploader@example.com' },
      document: {
        _id: 'doc-upl',
        title: 'Vehicle Registration (RC)',
        expiryDate: '2029-05-15'
      },
      daysLeft: 950,
      status: 'ACTIVE'
    });
    const uploadCmd = capturedCommands[capturedCommands.length - 1];
    assert.ok(uploadCmd.input.Message.Subject.Data.includes('Document Uploaded: Vehicle Registration (RC)'));

    assert.strictEqual(capturedCommands.length, 9, 'All 9 specialized templates must dispatch SendEmailCommand');
    recordPass('Test 6: All 9 application email templates dispatch with proper parameter mapping');
  } catch (err) {
    recordFail('Test 6: All 9 application email templates dispatch with proper parameter mapping', err);
  }

  // -------------------------------------------------------------
  // Test 7: Startup Connection Verification (verifySesConnection)
  // -------------------------------------------------------------
  try {
    // A. Healthy connection
    mockClientBehavior.sendQuotaSuccess = true;
    const isConnected = await emailService.verifySesConnection();
    assert.strictEqual(isConnected, true, 'Should verify successfully with GetSendQuota permission');

    // B. Least-privilege IAM policy (ses:SendEmail allowed, GetSendQuota denied)
    mockClientBehavior.sendQuotaSuccess = false;
    const accessDeniedErr = new Error('User is not authorized to perform: ses:GetSendQuota');
    accessDeniedErr.name = 'AccessDenied';
    mockClientBehavior.sendQuotaError = accessDeniedErr;

    const isLeastPrivilegeValid = await emailService.verifySesConnection();
    assert.strictEqual(isLeastPrivilegeValid, true, 'Should recognize authenticated least-privilege IAM credentials');

    // C. Invalid credentials (e.g. SignatureDoesNotMatch / InvalidClientTokenId)
    const invalidCredErr = new Error('The security token included in the request is invalid');
    invalidCredErr.name = 'InvalidClientTokenId';
    mockClientBehavior.sendQuotaError = invalidCredErr;

    const isInvalidRejected = await emailService.verifySesConnection();
    assert.strictEqual(isInvalidRejected, false, 'Should fail verification on invalid credentials');

    recordPass('Test 7: Connection verification handles standard, least-privilege IAM, and invalid states');
  } catch (err) {
    recordFail('Test 7: Connection verification handles standard, least-privilege IAM, and invalid states', err);
  } finally {
    mockClientBehavior.sendQuotaSuccess = true;
    mockClientBehavior.sendQuotaError = null;
  }

  // -------------------------------------------------------------
  // Test 8: Backward-Compatibility Aliases
  // -------------------------------------------------------------
  try {
    assert.strictEqual(typeof emailService.verifySmtpConnection, 'function');
    assert.strictEqual(typeof emailService.sendPasswordResetEmail, 'function');
    assert.strictEqual(emailService.verifySmtpConnection, emailService.verifySesConnection);

    recordPass('Test 8: Backward-compatibility aliases intact');
  } catch (err) {
    recordFail('Test 8: Backward-compatibility aliases intact', err);
  }

  // Restore original environment
  if (originalRegion) process.env.AWS_REGION = originalRegion;
  else delete process.env.AWS_REGION;
  if (originalSender) process.env.SES_FROM_EMAIL = originalSender;
  else delete process.env.SES_FROM_EMAIL;

  console.log('\n================================================================');
  console.log(`  Tests Complete: ${passed} Passed, ${failed} Failed`);
  console.log('================================================================\n');

  if (failed > 0) {
    process.exit(1);
  }
}

runSesTests().catch(err => {
  console.error('Fatal test error:', err);
  process.exit(1);
});
